const fail = (msg) => { console.error('FAIL:', msg); process.exit(1); };

if (TOPICS.length !== 21) fail(`考点应为 21 个，实为 ${TOPICS.length}`);
if (QUESTIONS.length !== 105) fail(`题目应为 105 道，实为 ${QUESTIONS.length}`);
const seenTopicIds = new Set();
for (const t of TOPICS) {
  if (seenTopicIds.has(t.id)) fail('重复考点 id: ' + t.id);
  seenTopicIds.add(t.id);
  if (topics.some((x) => x.id === t.id)) fail('考点 id 已存在: ' + t.id);
  if (!t.description || !Array.isArray(t.mastery) || t.mastery.length < 2) fail(`考点 ${t.id} 缺 description/mastery`);
}
const seenQ = new Set();
const dist = { A: 0, B: 0, C: 0, D: 0 };
const prompts = new Set();
const oldPrompts = new Set(questions.map((q) => q.prompt.trim()));
for (const q of QUESTIONS) {
  if (seenQ.has(q.id)) fail('重复题目 id: ' + q.id);
  seenQ.add(q.id);
  if (questions.some((x) => x.id === q.id)) fail('题目 id 已存在: ' + q.id);
  if (!seenTopicIds.has(q.topicId)) fail(`题目 ${q.id} 的考点不存在: ${q.topicId}`);
  if (!['A', 'B', 'C', 'D'].includes(q.answer)) fail(`题目 ${q.id} 答案非法: ${q.answer}`);
  if (!['basic', 'standard'].includes(q.difficulty)) fail(`题目 ${q.id} 难度非法`);
  if (!Array.isArray(q.choices) || q.choices.length !== 4) fail(`题目 ${q.id} 选项不是 4 个`);
  const keys = q.choices.map((c) => c.key);
  if (new Set(keys).size !== 4 || !keys.every((k) => ['A', 'B', 'C', 'D'].includes(k))) fail(`题目 ${q.id} 选项 key 异常`);
  if (!q.choices.some((c) => c.key === q.answer)) fail(`题目 ${q.id} 答案不在选项里`);
  if (!q.explanation || q.explanation.length < 30) fail(`题目 ${q.id} 解析太短或缺失`);
  if (!q.hint1) fail(`题目 ${q.id} 缺 hint1`);
  const p = q.prompt.trim();
  if (prompts.has(p)) fail('重复题干: ' + p);
  if (oldPrompts.has(p)) fail('题干与现有题库重复: ' + p);
  prompts.add(p);
  dist[q.answer]++;
}
for (const t of TOPICS) {
  const qs = QUESTIONS.filter((q) => q.topicId === t.id);
  if (qs.length !== 5) fail(`考点 ${t.id} 应为 5 题，实为 ${qs.length}`);
  if (qs.filter((q) => q.difficulty === 'basic').length !== 3) fail(`考点 ${t.id} 基础题应为 3 道`);
  if (qs.filter((q) => q.difficulty === 'standard').length !== 2) fail(`考点 ${t.id} 常规题应为 2 道`);
}
console.log('答案分布 A/B/C/D:', dist.A, dist.B, dist.C, dist.D);
if (Math.min(dist.A, dist.B, dist.C, dist.D) < 22 || Math.max(dist.A, dist.B, dist.C, dist.D) > 30) {
  fail('答案分布不均: ' + JSON.stringify(dist));
}

